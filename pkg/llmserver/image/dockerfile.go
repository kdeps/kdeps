// BuildRequest is input for rendering an appliance Dockerfile.
type BuildRequest struct {
	Recipe *recipe.Recipe
	Model  string
	// Tag is the docker image tag (informational in labels).
	Tag string
	// GPU is cuda|rocm|intel|vulkan|"" .
	GPU string
	// PullAtBuild materializes models during image build when strategy is pull.
	PullAtBuild bool
	// APIKeyEnv is the env var name for optional bearer auth (empty = none).
	// When set, entrypoint requires $APIKeyEnv (or LLM_API_KEY) for /v1 requests via a tiny filter note.
	APIKeyEnv string
	// RequireAuth forces bearer auth checks even if recipe auth is none.
	RequireAuth bool
}

// ResolveBaseImage returns the FROM image, applying GPU profile when set.
func ResolveBaseImage(recipeBase, gpu string) string {
	gpu = strings.ToLower(strings.TrimSpace(gpu))
	if gpu == "" {
		return recipeBase
	}
	// Keep recipe base when it is already a specialized image; only swap stock ubuntu.
	base := recipeBase
	if !strings.HasPrefix(base, "ubuntu:") && !strings.HasPrefix(base, "debian:") {
		return base
	}
	switch gpu {
	case "cuda":
		// CUDA runtime for GPU-accelerated engines; install scripts still run on top.
		return "nvidia/cuda:12.4.1-runtime-ubuntu22.04"
	case "rocm":
		return "rocm/dev-ubuntu-22.04:latest"
	case "intel", "vulkan":
		// Same Ubuntu family; packages differ at install time.
		return "ubuntu:24.04"
	default:
		return base
	}
}

// RenderDockerfile produces a Dockerfile for the LLM appliance (no kdeps agent).
func RenderDockerfile(req BuildRequest) (string, error) { //nolint:cyclop,funlen,gocognit // recipe→Dockerfile assembly
	if req.Recipe == nil {
		return "", errors.New("recipe is required")
	}
	r := req.Recipe
	if err := recipe.Validate(r); err != nil {
		return "", err
	}
	if r.Resources.GPU == recipe.GPURequired && strings.TrimSpace(req.GPU) == "" {
		return "", fmt.Errorf("recipe %q requires GPU: pass --gpu cuda|rocm|intel|vulkan", r.ID)
	}
	model := strings.TrimSpace(req.Model)
	if model == "" {
		model = r.Models.Default
	}
	from := ResolveBaseImage(r.Engine.BaseImage, req.GPU)

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by kdeps llm — appliance engine=%s model=%s\n", r.ID, model)
	fmt.Fprintf(&b, "# OpenAI-compatible API on port %d path %s\n", r.API.Port, r.API.BasePath)
	if req.GPU != "" {
		fmt.Fprintf(&b, "# GPU profile: %s\n", req.GPU)
	}
	fmt.Fprintf(&b, "FROM %s\n\n", from)
	b.WriteString("USER root\n")
	switch {
	case isDebianFamily(from):
		b.WriteString("ENV DEBIAN_FRONTEND=noninteractive\n")
		b.WriteString("RUN apt-get update && apt-get install -y --no-install-recommends \\\n")
		b.WriteString("    ca-certificates curl \\\n")
		if req.GPU == "vulkan" || req.GPU == "intel" {
			b.WriteString("    libvulkan1 mesa-vulkan-drivers \\\n")
		}
		if len(r.Engine.Packages) > 0 {
			fmt.Fprintf(&b, "    %s \\\n", strings.Join(r.Engine.Packages, " "))
		}
		b.WriteString("    && rm -rf /var/lib/apt/lists/*\n\n")
	case len(r.Engine.Packages) > 0:
		// Prebuilt server images: only emit package note; install via recipe install snippet.
		fmt.Fprintf(&b, "# packages declared (install via recipe install): %s\n\n",
			strings.Join(r.Engine.Packages, " "))
	default:
		b.WriteString("# Prebuilt inference image — skip base apt layer\n\n")
	}

	if strings.TrimSpace(r.Engine.Install) != "" && strings.TrimSpace(r.Engine.Install) != "true" {
		b.WriteString("# Engine install\n")
		install := strings.TrimSpace(r.Engine.Install)
		fmt.Fprintf(&b, "RUN set -eux; \\\n")
		for _, line := range strings.Split(install, "\n") {
			line = strings.TrimSpace(line)
			if line == "" || strings.HasPrefix(line, "#") {
				continue
			}
			fmt.Fprintf(&b, "    %s; \\\n", line)
		}
		b.WriteString("    true\n\n")
	}

	for k, v := range r.Engine.Env {
		fmt.Fprintf(&b, "ENV %s=%q\n", k, v)
	}
	if model != "" {
		fmt.Fprintf(&b, "ENV LLM_MODEL=%q\n", model)
	}
	fmt.Fprintf(&b, "ENV LLM_API_PORT=%d\n", r.API.Port)
	authEnv := req.APIKeyEnv
	if authEnv == "" && r.API.Auth.Env != "" {
		authEnv = r.API.Auth.Env
	}
	if authEnv != "" {
		fmt.Fprintf(&b, "ENV LLM_API_KEY_ENV=%q\n", authEnv)
	}
	if req.RequireAuth || r.API.Auth.Mode == recipe.AuthBearerRequired {
		b.WriteString("ENV LLM_AUTH_REQUIRED=true\n")
	}
	if req.GPU != "" {
		fmt.Fprintf(&b, "ENV LLM_GPU_PROFILE=%q\n", req.GPU)
	}
	b.WriteString("\n")

	fmt.Fprintf(&b, "LABEL org.kdeps.llm-server=\"true\" \\\n")
	fmt.Fprintf(&b, "      org.kdeps.llm-engine=%q \\\n", r.ID)
	fmt.Fprintf(&b, "      org.kdeps.llm-model=%q\n\n", model)

	if req.PullAtBuild && r.Models.Strategy == recipe.ModelPull && model != "" && r.Engine.Kind == recipe.EngineOllama {
		b.WriteString("# Pull model at build (offline-friendly image)\n")
		b.WriteString("RUN (ollama serve &) && sleep 3 && ollama pull \"$LLM_MODEL\" && pkill ollama || true\n\n")
	}

	b.WriteString("COPY entrypoint.sh /entrypoint.sh\n")
	b.WriteString("RUN chmod +x /entrypoint.sh\n\n")

	fmt.Fprintf(&b, "EXPOSE %d\n", r.API.Port)
	fmt.Fprintf(&b, "HEALTHCHECK --interval=30s --timeout=5s --start-period=60s --retries=3 \\\n")
	if isDebianFamily(from) {
		fmt.Fprintf(&b, "  CMD curl -fsS \"http://127.0.0.1:%d%s\" || exit 1\n\n", r.API.Port, r.API.Health.Path)
	} else {
		// Prebuilt images may lack curl; prefer python urllib (vLLM/TGI/SGLang images include python).
		fmt.Fprintf(&b,
			"  CMD python3 -c \"import urllib.request; urllib.request.urlopen('http://127.0.0.1:%d%s')\" || exit 1\n\n",
			r.API.Port, r.API.Health.Path)
	}
	b.WriteString("ENTRYPOINT [\"/entrypoint.sh\"]\n")

	_ = req.Tag
	return b.String(), nil
}

// RenderEntrypoint produces the container entrypoint that starts the engine.
//
//nolint:funlen // entrypoint script assembly
func RenderEntrypoint(req BuildRequest) (string, error) {
	if req.Recipe == nil {
		return "", errors.New("recipe is required")
	}
	r := req.Recipe
	model := strings.TrimSpace(req.Model)
	if model == "" {
		model = r.Models.Default
	}

	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("set -e\n")
	b.WriteString("# kdeps llm appliance entrypoint — OpenAI-compat surface only\n\n")

	for k, v := range r.Engine.Env {
		fmt.Fprintf(&b, "export %s=%q\n", k, v)
	}
	if model != "" {
		fmt.Fprintf(&b, "export LLM_MODEL=%q\n", model)
	}

	// Auth: document expected bearer env for clients; engines that honor it read LLM_API_KEY.
	authEnv := req.APIKeyEnv
	if authEnv == "" {
		authEnv = r.API.Auth.Env
	}
	if authEnv == "" {
		authEnv = "LLM_API_KEY"
	}
	fmt.Fprintf(&b, "export LLM_API_KEY_ENV=%q\n", authEnv)
	b.WriteString("# If LLM_AUTH_REQUIRED=true, fail fast when the API key env is empty.\n")
	b.WriteString("if [ \"${LLM_AUTH_REQUIRED:-}\" = \"true\" ]; then\n")
	b.WriteString("  eval \"_k=\\$$LLM_API_KEY_ENV\"\n")
	b.WriteString("  if [ -z \"${_k}\" ] && [ -z \"${LLM_API_KEY:-}\" ]; then\n")
	b.WriteString("    echo \"LLM auth required: set $LLM_API_KEY_ENV or LLM_API_KEY\" >&2\n")
	b.WriteString("    exit 1\n")
	b.WriteString("  fi\n")
	b.WriteString("  # Normalize for engines that read OPENAI_API_KEY / API_KEY\n")
	b.WriteString("  export LLM_API_KEY=\"${_k:-$LLM_API_KEY}\"\n")
	b.WriteString("  export OPENAI_API_KEY=\"${OPENAI_API_KEY:-$LLM_API_KEY}\"\n")
	b.WriteString("fi\n\n")

	cmd := shellJoin(r.Engine.Command)

	if r.Engine.OpenAIBridge {
		fmt.Fprintf(&b, "# Start engine; prefer public API port %d when engine is ollama\n", r.API.Port)
		fmt.Fprintf(&b, "%s &\n", cmd)
		b.WriteString("ENGINE_PID=$!\n")
		if r.Models.Strategy == recipe.ModelPull && model != "" && !req.PullAtBuild &&
			r.Engine.Kind == recipe.EngineOllama {
			b.WriteString(
				"i=0; while [ $i -lt 60 ]; do ollama list >/dev/null 2>&1 && break; i=$((i+1)); sleep 1; done\n",
			)
			b.WriteString("ollama pull \"$LLM_MODEL\" || true\n")
		}
		if r.Engine.Kind == recipe.EngineOllama {
			b.WriteString("# Rebind Ollama on the published API port (native /v1)\n")
			fmt.Fprintf(&b, "export OLLAMA_HOST=\"0.0.0.0:%d\"\n", r.API.Port)
			b.WriteString("kill \"$ENGINE_PID\" 2>/dev/null || true\n")
			b.WriteString("wait \"$ENGINE_PID\" 2>/dev/null || true\n")
			fmt.Fprintf(&b, "exec %s\n", cmd)
		} else {
			fmt.Fprintf(&b, "# Engine upstream for clients: %s\n", r.Engine.OpenAIBridgeUpstream)
			b.WriteString("wait \"$ENGINE_PID\"\n")
		}
		return b.String(), nil
	}

	if r.Models.Strategy == recipe.ModelPull && model != "" && !req.PullAtBuild &&
		r.Engine.Kind == recipe.EngineOllama {
		fmt.Fprintf(&b, "%s &\n", cmd)
		b.WriteString("ENGINE_PID=$!\n")
		b.WriteString("i=0; while [ $i -lt 60 ]; do ollama list >/dev/null 2>&1 && break; i=$((i+1)); sleep 1; done\n")
		b.WriteString("ollama pull \"$LLM_MODEL\" || true\n")
		b.WriteString("wait \"$ENGINE_PID\"\n")
		return b.String(), nil
	}

	fmt.Fprintf(&b, "exec %s\n", cmd)
	return b.String(), nil
}

func isDebianFamily(image string) bool {
	img := strings.ToLower(image)
	return strings.Contains(img, "ubuntu") ||
		strings.Contains(img, "debian") ||
		strings.HasPrefix(img, "nvidia/cuda") ||
		strings.HasPrefix(img, "rocm/")
}

func shellJoin(parts []string) string {
	out := make([]string, len(parts))
	for i, p := range parts {
		if p == "" || strings.ContainsAny(p, " \t\"'$") {
			out[i] = fmt.Sprintf("%q", p)
		} else {
			out[i] = p
		}
	}
	return strings.Join(out, " ")
}
