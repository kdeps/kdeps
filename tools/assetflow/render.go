package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

// stringList is a Go []string literal of ss.
func stringList(ss []string) string {
	var b strings.Builder
	b.WriteString("[]string{")
	for i, s := range ss {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", s)
	}
	b.WriteString("}")
	return b.String()
}

// render writes the flows as pkg/assets/setflow_gen.go.
func render(flows map[string]Flow) ([]byte, error) {
	sets := make([]string, 0, len(flows))
	for s := range flows {
		sets = append(sets, s)
	}
	sort.Strings(sets)
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./tools/assetflow; DO NOT EDIT.\n\n")
	b.WriteString("package assets\n\n")
	b.WriteString("// generatedFlows is where kdeps uses each set: the story on the function\n")
	b.WriteString("// that uses it (//kdeps:flow), and its mode, users and code path, read\n")
	b.WriteString("// from the call graph.\n")
	b.WriteString("//\n//nolint:gochecknoglobals,lll // generated table\n")
	b.WriteString("var generatedFlows = map[string]SetInfo{\n")
	for _, s := range sets {
		f := flows[s]
		fmt.Fprintf(&b, "\t%q: {\n\t\tMode: %q,\n\t\tFlow: []FlowStep{\n", s, f.Mode)
		for _, st := range f.Steps {
			if st.Here {
				fmt.Fprintf(&b, "\t\t\t{Label: %q, Here: true},\n", st.Label)
			} else {
				fmt.Fprintf(&b, "\t\t\t{Label: %q},\n", st.Label)
			}
		}
		b.WriteString("\t\t},\n\t\tUsedBy: " + stringList(f.UsedBy) + ",\n")
		b.WriteString("\t\tCode:   " + stringList(f.Code) + ",\n\t},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
