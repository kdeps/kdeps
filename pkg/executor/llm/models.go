package llm

import (
	"embed"
	"errors"
	"fmt"
	"io/fs"
	"path"

	"github.com/kdeps/kdeps/v2/pkg/assets"
)

// modelsSet is the asset set (and embed dir) holding the model registries,
// generated by tools/llamafile-harvester/harvest.py.
const modelsSet = "models"

const (
	llamafileRegistryItem = "llamafile"
	ggufRegistryItem      = "gguf"
)

//go:embed models/*.yaml
var stockModels embed.FS

// modelsFSFunc returns the registries as loaders see them: compiled-in files
// replaced by newer downloads (`kdeps update models`). Tests override it.
//
//nolint:gochecknoglobals // test hook
var modelsFSFunc = func() fs.FS {
	return assets.Overlay(modelsSet, stockModels, modelsSet, assets.Root())
}

//nolint:gochecknoinits // registers the model registries as a versioned asset set
func init() {
	assets.RegisterSeed(modelsSet, assets.Seed{
		FS:       stockModels,
		Dir:      modelsSet,
		Validate: validateModelRegistry,
		// Default models and aliases resolve through these; they can be
		// updated but not removed.
		Required: []string{llamafileRegistryItem, ggufRegistryItem},
	})
}

func validateModelRegistry(data []byte, name string) error {
	var n int
	switch name {
	case llamafileRegistryItem:
		if v := parseLlamafileYAML(data); v != nil {
			n = len(v.Llamafiles)
		}
	case ggufRegistryItem:
		if v := parseGGUFYAML(data); v != nil {
			n = len(v.GGUFs)
		}
	default:
		return fmt.Errorf("unknown model registry %q", name)
	}
	if n == 0 {
		return errors.New("model registry has no entries")
	}
	return nil
}

// readModelRegistry returns the in-use bytes of one registry item, or nil.
func readModelRegistry(name string) []byte {
	data, err := fs.ReadFile(modelsFSFunc(), path.Join(modelsSet, name+".yaml"))
	if err != nil {
		return nil
	}
	return data
}
