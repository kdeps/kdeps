package executor_test

import (
	"encoding/json"
	"log/slog"
	"net/http"
	"net/http/httptest"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/kdeps/kdeps/v3/pkg/domain"
	"github.com/kdeps/kdeps/v3/pkg/executor"
	executorLLM "github.com/kdeps/kdeps/v3/pkg/executor/llm"
)

type runMemory struct {
	executor.AgentMemoryStore
	saved map[string]string
}

func (m *runMemory) Set(k, v string) error { m.saved[k] = v; return nil }

// A workflow chat calls memory_save by name; with a memory store on the
// engine (kdeps run --memory) the fact lands in it.
func TestWorkflowChat_MemoryToolUsesRunStore(t *testing.T) {
	t.Setenv("HOME", t.TempDir())
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodPost {
			_, _ = w.Write([]byte(`{"data":[{"id":"fake"}]}`))
			return
		}
		var body struct {
			Messages []struct {
				Role    string `json:"role"`
				Content string `json:"content"`
			} `json:"messages"`
		}
		_ = json.NewDecoder(r.Body).Decode(&body)
		reply := `{"name": "memory_save", "arguments": {"key": "color", "value": "teal"}}`
		if last := body.Messages[len(body.Messages)-1]; last.Role == "tool" {
			reply = "SAVED " + last.Content
		}
		raw, _ := json.Marshal(map[string]any{
			"id": "x", "object": "chat.completion", "model": "fake",
			"choices": []any{map[string]any{"index": 0, "finish_reason": "stop",
				"message": map[string]any{"role": "assistant", "content": reply}}},
		})
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write(raw)
	}))
	t.Cleanup(srv.Close)
	t.Setenv(executorLLM.OverrideURLEnv, srv.URL)

	store := &runMemory{saved: map[string]string{}}
	wf := &domain.Workflow{
		APIVersion: "kdeps.io/v1",
		Kind:       "Workflow",
		Metadata:   domain.WorkflowMetadata{Name: "mem", Version: "1.0.0", TargetActionID: "ask"},
		Resources: []*domain.Resource{{
			ActionID: "ask",
			Chat: &domain.ChatConfig{
				Model: "fake", Role: "user", Prompt: "remember teal", Tools: []domain.Tool{{Name: "memory_save"}},
			},
		}},
	}
	engine := executor.NewEngine(t.Context(), slog.Default())
	registry := executor.NewRegistry()
	registry.SetLLMExecutor(executorLLM.NewAdapter(t.Context(), srv.URL))
	engine.SetRegistry(registry)
	engine.SetAgentMemoryStore(store)
	out, err := engine.Execute(wf, nil)
	require.NoError(t, err)
	raw, _ := json.Marshal(out)
	assert.Contains(t, string(raw), "SAVED")
	assert.Equal(t, "teal", store.saved["color"])
}
