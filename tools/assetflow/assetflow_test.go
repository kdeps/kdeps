func outerForTest() (func(), func() func()) {
	a := func() {}
	b := func() func() { return func() {} }
	return a, b
}

func TestSSAName(t *testing.T) {
	a, b := outerForTest()
	assert.True(t, strings.HasSuffix(ssaName(a), ".outerForTest$1"), ssaName(a))
	assert.True(t, strings.HasSuffix(ssaName(b()), ".outerForTest$2$1"), ssaName(b()))
	assert.True(t, strings.HasSuffix(ssaName(TestSSAName), ".TestSSAName"))
	var none func()
	assert.Empty(t, ssaName(none))
}

func TestCommandEntries(t *testing.T) {
	root := &cobra.Command{Use: "kdeps", RunE: func(*cobra.Command, []string) error { return nil }}
	sub := &cobra.Command{Use: "knowledge"}
	leaf := &cobra.Command{Use: "check", RunE: func(*cobra.Command, []string) error { return nil }}
	sub.AddCommand(leaf)
	root.AddCommand(sub)
	got := map[string]bool{}
	for _, l := range commandEntries(root) {
		got[l] = true
	}
	assert.True(t, got[rootLabel])
	assert.True(t, got["kdeps knowledge check"])
}

func TestModeAndRank(t *testing.T) {
	assert.Equal(t, "agent", modeOf([]string{rootLabel, "/help"}))
	assert.Equal(t, "workflow", modeOf([]string{"kdeps run"}))
	assert.Equal(t, "both", modeOf([]string{"/help", "kdeps validate"}))
	assert.Equal(t, "cli", modeOf([]string{"kdeps llm list"}))
	assert.Less(t, entryRank(rootLabel), entryRank("/help"))
	assert.Less(t, entryRank("/help"), entryRank("kdeps run"))
	assert.Less(t, entryRank("kdeps run"), entryRank("kdeps llm"))
	assert.Less(t, entryRank("kdeps llm"), entryRank(startupName))
}

func TestRender(t *testing.T) {
	src, err := render(map[string]Flow{"tools": {Mode: "agent", UsedBy: []string{rootLabel},
		Steps: []Step{{Label: rootLabel}, {Label: "agent.use uses tools", Here: true}}}})
	assert.NoError(t, err)
	assert.Contains(t, string(src), "// Code generated by go run ./tools/assetflow; DO NOT EDIT.")
	assert.Contains(t, string(src), `{Label: "agent.use uses tools", Here: true}`)
}

func TestParseStory(t *testing.T) {
	set, steps, err := parseStory("harness: you type > [the system prompt is built] > the model answers")
	assert.NoError(t, err)
	assert.Equal(t, "harness", set)
	assert.Equal(t, []Step{{Label: "you type"}, {Label: "the system prompt is built", Here: true}, {Label: "the model answers"}}, steps)

	_, _, err = parseStory("no set here > [x]")
	assert.ErrorContains(t, err, "needs \"<set>: step")
	_, _, err = parseStory("tools: a > b")
	assert.ErrorContains(t, err, "found 0")
	_, _, err = parseStory("tools: [a] > [b]")
	assert.ErrorContains(t, err, "found 2")
}

