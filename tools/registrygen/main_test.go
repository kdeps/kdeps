func TestCamel(t *testing.T) {
	assert.Equal(t, "AutoCompact", camel("auto-compact"))
	assert.Equal(t, "Rag", camel("rag"))
	assert.Equal(t, "OpenrouterNoise", camel("openrouter-noise"))
}

func TestRenderEvents(t *testing.T) {
	src, err := renderEvents([]string{"auto-compact", "fold"})
	require.NoError(t, err)
	out := string(src)
	assert.True(t, strings.HasPrefix(out, "// Code generated by tools/registrygen; DO NOT EDIT."))
	assert.Contains(t, out, "package agent")
	assert.Regexp(t, `eventAutoCompact\s+= "auto-compact"`, out)
	assert.Regexp(t, `eventFold\s+= "fold"`, out)
}

func TestWriteTableRejectsUnknownShelf(t *testing.T) {
	var b bytes.Buffer
	err := writeTable(&b, "setShelf", "test", map[string]string{"tools": "nope"}, []string{"tools"})
	require.Error(t, err)
	assert.Contains(t, err.Error(), `"nope" is not a shelf`)
}

func TestRunWritesThenCheckPasses(t *testing.T) {
	root := t.TempDir()
	require.NoError(t, os.MkdirAll(filepath.Join(root, "assets", "events"), 0o755))
	require.NoError(t, os.MkdirAll(filepath.Join(root, "pkg", "agent"), 0o755))
	require.NoError(t, os.MkdirAll(filepath.Join(root, "pkg", "assets"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, "assets", "events", "fold.yaml"),
		[]byte("version: 1.0.0\nname: fold\nitems: 3\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(root, "assets", "shelves.yaml"),
		[]byte("shelves:\n  - tools\nsets:\n  tools: tools\nitems: {}\n"), 0o644))

	require.Error(t, run(root, true), "a missing generated file is stale")
	require.NoError(t, run(root, false))
	require.NoError(t, run(root, true), "a freshly written file is not stale")
}

