#!/usr/bin/env python3
"""Harvest OpenRouter's free text models into assets/models/openrouter.yaml.

A model is free when its prompt price and completion price are both zero,
any per-request price is zero, and it outputs text only (music and image
models bill outside the token price and are left out). The list is sorted
by id. A changed registry gets its patch version bumped.

    python3 harvest.py                     # print the registry
    python3 harvest.py --write             # write assets/models/openrouter.yaml
    python3 harvest.py --write --output d  # write into another directory
    python3 harvest.py --input payload.json --write
"""

import argparse
import json
import os
import re
import sys
import urllib.request
from decimal import Decimal, InvalidOperation

HERE = os.path.dirname(os.path.abspath(__file__))
MODELS_DIR = os.path.normpath(os.path.join(HERE, "..", "..", "assets", "models"))
MODELS_URL = "https://openrouter.ai/api/v1/models"
REGISTRY_NAME = "openrouter.yaml"

REGISTRY_HEADER = (
    "# OpenRouter free model catalog: text models with a zero prompt and completion price.\n"
    "# Generated by tools/openrouter-harvester/harvest.py from the OpenRouter models API; do not edit by hand.\n"
    "# Entries: {count}\n"
)


def zero_price(value):
    """True when value is a numeric zero. None and blank are not zero."""
    if value is None or value == "":
        return False
    try:
        return Decimal(str(value)) == 0
    except (InvalidOperation, ValueError):
        return False


def is_free_model(model):
    """A free chat model: zero token prices and text as its only output."""
    if not model.get("id"):
        return False
    pricing = model.get("pricing") or {}
    if "prompt" not in pricing or "completion" not in pricing:
        return False
    if not zero_price(pricing.get("prompt")) or not zero_price(pricing.get("completion")):
        return False
    if "request" in pricing and not zero_price(pricing.get("request")):
        return False
    outputs = (model.get("architecture") or {}).get("output_modalities")
    if outputs is None:
        outputs = ["text"]
    if outputs != ["text"]:
        return False
    ctx = model.get("context_length") or 0
    max_out = (model.get("top_provider") or {}).get("max_completion_tokens") or 0
    return ctx > 0 and max_out > 0


# A parameter count in a model id, such as 550b in nvidia/nemotron-3-ultra-550b-a55b.
PARAMS_RE = re.compile(r"(?i)(\d+(?:\.\d+)?)b\b")


def parameter_count(model_id):
    """Largest parameter count in billions named in the id, or 0 when none is named."""
    counts = [float(m.group(1)) for m in PARAMS_RE.finditer(model_id)]
    return max(counts, default=0)


def to_entry(model):
    """One models/openrouter.yaml row."""
    arch = model.get("architecture") or {}
    params = model.get("supported_parameters") or []
    name = " ".join(str(model.get("name") or model["id"]).split())
    return {
        "id": model["id"],
        "backend": "openrouter",
        "desc": name,
        "envVar": "OPENROUTER_API_KEY",
        "thinking": "reasoning" in params,
        "images": "image" in (arch.get("input_modalities") or []),
        "contextWindow": int(model["context_length"]),
        "maxOutputTokens": int(model["top_provider"]["max_completion_tokens"]),
        "params": parameter_count(model["id"]),
    }


def free_entries(payload):
    """Free models from an OpenRouter /models payload, sorted by id."""
    data = payload.get("data") if isinstance(payload, dict) else None
    if not isinstance(data, list):
        raise ValueError("models payload has no data list")
    entries = [to_entry(m) for m in data if is_free_model(m)]
    entries.sort(key=lambda e: e["id"])
    return entries


def yaml_quote(value):
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def entry_lines(entry):
    lines = [
        f"  - id: {yaml_quote(entry['id'])}",
        "    backend: openrouter",
        f"    desc: {yaml_quote(entry['desc'])}",
        "    envVar: OPENROUTER_API_KEY",
    ]
    if entry["thinking"]:
        lines.append("    thinking: true")
    if entry["images"]:
        lines.append("    images: true")
    lines.append(f"    contextWindow: {entry['contextWindow']}")
    lines.append(f"    maxOutputTokens: {entry['maxOutputTokens']}")
    if entry["params"]:
        lines.append(f"    params: {entry['params']:g}")
    lines.append("")
    return lines


def read_registry(path):
    """Return (version, body) of an existing registry, or (None, None)."""
    if not path:
        return None, None
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    except FileNotFoundError:
        return None, None
    match = re.search(r"^version:\s*\"?([0-9][^\"\s]*)\"?\s*$", text, re.M)
    if not match:
        return None, None
    return match.group(1), text[match.end():].lstrip("\n")


def bump_patch(version):
    major, minor, patch = (version.split("-")[0].split(".") + ["0", "0"])[:3]
    return f"{major}.{minor}.{int(patch) + 1}"


def registry_body(entries):
    lines = ["models:"]
    for entry in entries:
        lines += entry_lines(entry)
    return "\n".join(lines).rstrip("\n") + "\n"


def registry_text(path, entries):
    """Same version when entries are unchanged, patch-bumped when they changed, 1.0.0 when new."""
    body = registry_body(entries)
    old_version, old_body = read_registry(path)
    if old_version is None:
        version = "1.0.0"
    elif old_body == body:
        version = old_version
    else:
        version = bump_patch(old_version)
    return REGISTRY_HEADER.format(count=len(entries)) + f"version: {version}\n" + body


def fetch_models(url):
    req = urllib.request.Request(url, headers={"User-Agent": "kdeps-openrouter-harvester"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return json.load(resp)


def load_payload(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Harvest OpenRouter free models")
    parser.add_argument("--write", action="store_true", help="Write the registry file")
    parser.add_argument("--output", default=None, help="Output directory (with --write)")
    parser.add_argument("--input", default=None, help="Read a saved /models payload instead of the API")
    args = parser.parse_args(argv)

    payload = load_payload(args.input) if args.input else fetch_models(MODELS_URL)
    try:
        entries = free_entries(payload)
    except ValueError as err:
        print(f"openrouter harvest: {err}", file=sys.stderr)
        return 1
    if not entries:
        print("openrouter harvest: no free text models", file=sys.stderr)
        return 1

    out_dir = args.output if args.output else MODELS_DIR
    path = os.path.join(out_dir, REGISTRY_NAME) if args.write else None
    text = registry_text(path, entries)
    if not args.write:
        sys.stdout.write(text)
        return 0
    os.makedirs(out_dir, exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
